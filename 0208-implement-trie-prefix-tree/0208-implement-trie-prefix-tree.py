from collections import defaultdict
class Trie:
    # a ->p ->p ->l ->e(end = True)
    # {a:{p:1,x:1}}
    def __init__(self):
        self.root = defaultdict(dict)
    def insert(self, word: str) -> None:
        node = self.root
        for c in word:
            if c not in node:
                node[c] = {}
            node = node[c]
        node[1] = {}
    def search(self, word: str) -> bool:
        node = self.root
        for c in word:
            if c not in node:
                return False
            node = node[c]
        return 1 in node

    def startsWith(self, prefix: str) -> bool:
        node = self.root
        for c in prefix:
            if c not in node:
                return False
            node = node[c]
        return True
